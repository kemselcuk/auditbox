-- AuditBox V2: convert the single "events" table to a monthly RANGE-partitioned
-- table on occurred_at (Milestone 11.1, decision D21).
--
-- Plain forward-only SQL per Flyway conventions: no procedures, no downgrade path.
-- All existing rows are copied, then the final table keeps the name "events", so the
-- single-logical-table boundary and the API contract are unchanged (D21).
--
-- What changes structurally:
--   * The parent table is PARTITION BY RANGE (occurred_at). Monthly partitions are
--     named events_YYYY_MM with half-open bounds [month start UTC, next month start
--     UTC); the app already normalizes occurredAt to UTC (D10), so the boundaries are
--     stable wall-clock instants.
--   * A DEFAULT partition (events_default) catches any occurredAt inside the
--     documented API range (0001-01-01..9999-12-31, D13) that no monthly partition
--     covers yet — every API-legal event stays storable. Partition maintenance
--     (creating/rotating the monthly window) is Milestone 11.2, not this migration:
--     the DO block below only builds the initial window relative to the run date.
--   * A partitioned unique index must include the partition key, so the old table
--     constraint uq_events_event_id on (event_id) cannot be kept as-is. It becomes a
--     UNIQUE INDEX on (occurred_at, event_id) — the DB keeps only (occurredAt,
--     eventId) uniqueness. Global per-eventId uniqueness is restored in the
--     application: every write serializes on a transaction-scoped advisory lock
--     keyed by the eventId (EventService, D21), so one eventId can never produce two
--     rows even across different occurredAt months.
--   * Because the index alone no longer guards global eventId uniqueness, GET
--     /api/v1/events/{eventId} and the idempotency pre-check must scan every
--     partition's (event_id) index — they stay index-assisted via the added
--     non-unique ix_events_event_id index on the parent.
--
-- Decision references: D1 (event contract), D3 (keyset pagination order),
-- D4 (duplicate handling), D10 (UTC/hash normalization), D21 (partitioning).

-- ---------------------------------------------------------------------------
-- 1. Take the V1 table aside. Rows stay here until step 5 copies them over; the
--    table is dropped at the end of this script (no data-loss window). Its
--    constraint/index names are renamed first, because PostgreSQL keeps object
--    names on a table rename and the new structure reuses the classic names.
-- ---------------------------------------------------------------------------
ALTER TABLE events RENAME TO events_v1;

ALTER TABLE events_v1 RENAME CONSTRAINT events_pkey TO events_v1_pkey;
ALTER TABLE events_v1 RENAME CONSTRAINT uq_events_event_id TO events_v1_uq_events_event_id;
ALTER INDEX ix_events_occurred_at_event_id RENAME TO events_v1_ix_occurred_at_event_id;
ALTER INDEX ix_events_user_id RENAME TO events_v1_ix_user_id;
ALTER INDEX ix_events_event_type RENAME TO events_v1_ix_event_type;
ALTER INDEX ix_events_source RENAME TO events_v1_ix_source;

-- ---------------------------------------------------------------------------
-- 2. New partitioned parent with the V1 columns (order kept). PostgreSQL 18
--    supports identity columns on partitioned tables; GENERATED BY DEFAULT keeps
--    plain inserts possible for tests and tooling (and the explicit-id row copy
--    below). A partitioned primary key must include the partition key: the PK is
--    (occurred_at, id) instead of (id).
-- ---------------------------------------------------------------------------
CREATE TABLE events (
    -- Identity: GENERATED BY DEFAULT keeps plain inserts possible for tests and tooling.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    -- Content fields as received from the client (D1). content_hash covers exactly
    -- these five fields plus metadata; it is the canonicalization documented on
    -- io.auditbox.events.EventContentHasher.
    event_id    TEXT        NOT NULL,
    user_id     TEXT        NOT NULL,
    event_type  TEXT        NOT NULL,
    source      TEXT        NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,

    -- Server-side fields: received_at is set by the database on insert and is never
    -- part of the content hash.
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Optional client metadata (D1). Absent and explicit null are the same content.
    metadata    JSONB       NULL,

    -- Lowercase hex SHA-256 of the canonical JSON of the content fields (D4, T2.2).
    content_hash TEXT       NOT NULL,

    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Partitioned-table primary key: must include the partition key occurred_at
    -- (D21). Row identity inside a partition comes from the identity column.
    PRIMARY KEY (occurred_at, id)
) PARTITION BY RANGE (occurred_at);

-- ---------------------------------------------------------------------------
-- 3. Initial monthly window: (current month - 25 months) through (current month
--    + 3 months), relative to the migration run. The retention job (Milestone 11.2)
--    maintains this window later. The timezone is pinned to UTC both when truncating
--    and when formatting (D10: the app already normalizes occurredAt to UTC), so the
--    bounds do not depend on the migration session's timezone.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    first_day      TIMESTAMP;  -- UTC wall-clock month start, tz-independent
    window_month   TIMESTAMP;
    lower_bound    TIMESTAMPTZ;
    upper_bound    TIMESTAMPTZ;
    part_name      TEXT;
    month_offset   INT;
BEGIN
    first_day := date_trunc('month', now() AT TIME ZONE 'UTC');
    FOR month_offset IN -25..3 LOOP
        window_month := first_day + make_interval(months => month_offset);
        part_name    := 'events_' || to_char(window_month, 'YYYY_MM');
        lower_bound  := window_month AT TIME ZONE 'UTC';
        upper_bound  := (window_month + interval '1 month') AT TIME ZONE 'UTC';
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS %I PARTITION OF events FOR VALUES FROM (%L) TO (%L)',
            part_name, lower_bound, upper_bound);
    END LOOP;
END
$$;

-- ---------------------------------------------------------------------------
-- 4. DEFAULT partition: every API-legal occurredAt (0001-01-01..9999-12-31, D13)
--    that falls outside the managed monthly window stays storable (D21). Rows here
--    are moved into their monthly partition by the later maintenance task.
-- ---------------------------------------------------------------------------
CREATE TABLE events_default PARTITION OF events DEFAULT;

-- ---------------------------------------------------------------------------
-- 5. Copy the existing rows (keeping ids, received_at and created_at verbatim).
-- ---------------------------------------------------------------------------
INSERT INTO events (
    id, event_id, user_id, event_type, source, occurred_at,
    received_at, metadata, content_hash, created_at)
SELECT
    id, event_id, user_id, event_type, source, occurred_at,
    received_at, metadata, content_hash, created_at
FROM events_v1;

-- ---------------------------------------------------------------------------
-- 6. Indexes, all (re)created on the partitioned parent so each partition carries
--    its own backing index:
--   * uq_events_event_id — kept name, now a UNIQUE INDEX on (occurred_at,
--     event_id) instead of the V1 table constraint on (event_id): a partitioned
--     unique index must include the partition key (D21). Rejects a duplicate
--     (occurredAt, eventId) pair with SQLState 23505.
--   * ix_events_occurred_at_event_id — keyset order of D3.
--   * ix_events_event_id — NEW: GET /api/v1/events/{eventId} and the write-path
--     idempotency lookup scan every partition's index (documented trade-off, D21).
--   * ix_events_user_id / ix_events_event_type / ix_events_source — Stage 4 filters.
-- ---------------------------------------------------------------------------
CREATE UNIQUE INDEX uq_events_event_id ON events (occurred_at, event_id);

CREATE INDEX ix_events_occurred_at_event_id
    ON events (occurred_at DESC, event_id DESC);

CREATE INDEX ix_events_event_id ON events (event_id);

CREATE INDEX ix_events_user_id ON events (user_id);
CREATE INDEX ix_events_event_type ON events (event_type);
CREATE INDEX ix_events_source ON events (source);

-- ---------------------------------------------------------------------------
-- 7. Push the identity sequence past the copied maximum id (the copy inserted
--    explicit ids). With rows present: setval(max, is_called=true) → next value
--    max+1. On an empty table: setval(1, is_called=false) → next value 1.
-- ---------------------------------------------------------------------------
SELECT setval(
    pg_get_serial_sequence('events', 'id'),
    COALESCE((SELECT MAX(id) FROM events), 1),
    EXISTS(SELECT 1 FROM events));

-- ---------------------------------------------------------------------------
-- 8. Drop the staging table (and its own identity sequence).
-- ---------------------------------------------------------------------------
DROP TABLE events_v1;
