package io.auditbox.events;

import java.time.OffsetDateTime;

import org.hibernate.annotations.Generated;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

import tools.jackson.databind.JsonNode;

/**
 * JPA entity mapped exactly to the {@code events} table of {@code V1__create_events.sql}
 * (plan tasks T2.1 and T3.1/T3.2, decision D11). The schema is owned by Flyway and
 * Hibernate only validates ({@code ddl-auto: validate}).
 *
 * <h2>Mapping decisions</h2>
 *
 * <ul>
 *   <li><strong>Timestamps are {@link OffsetDateTime} (not {@link java.time.Instant}).</strong>
 *       The API contract is a strict ISO-8601 date-time with an offset (D10), so
 *       {@code OffsetDateTime} is the natural type for the value a client sends. PostgreSQL
 *       {@code timestamptz} normalizes to UTC at microsecond precision; hashing also
 *       normalizes to the same instant (D10), so the offset form the API returns never
 *       changes content identity — a retry that echoes the API-returned {@code occurredAt}
 *       hashes identically.</li>
 *   <li><strong>{@code metadata} jsonb.</strong> Mapped as a Jackson 3 {@code JsonNode} with
 *       {@code @JdbcTypeCode(SqlTypes.JSON)}. Hibernate delegates the actual (de)serialization
 *       to the application-provided {@code FormatMapper}
 *       ({@code hibernate.type.json_format_mapper}, registered in
 *       {@link JsonFormatMapperConfiguration}) so numbers stay exact
 *       {@code BigDecimal}s (D10) and the column stays real {@code jsonb}. An explicit JSON
 *       null and an absent metadata are both stored as SQL {@code NULL} (D10).</li>
 *   <li><strong>Server-side columns.</strong> {@code received_at} and {@code created_at} are
 *       generated by the database ({@code DEFAULT now()}, DB clock at insert — D11). They are
 *       kept out of the INSERT statement ({@code insertable = false}) and read back right
 *       after the insert via {@link Generated @Generated} (its default event is
 *       {@code INSERT} and it is not writable). {@code created_at} is row bookkeeping and is
 *       never exposed by the API.</li>
 * </ul>
 */
@Entity
@Table(name = "events")
public class EventEntity {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	private Long id;

	/**
	 * Client-generated event identifier (D1). Backed by the unique constraint
	 * {@code uq_events_event_id}; the insert flow catches its violation and resolves
	 * idempotent retries and conflicts against the stored row (D4).
	 */
	@Column(name = "event_id", nullable = false)
	private String eventId;

	@Column(name = "user_id", nullable = false)
	private String userId;

	@Column(name = "event_type", nullable = false)
	private String eventType;

	@Column(nullable = false)
	private String source;

	/**
	 * When the event occurred, as claimed by the client (D1). Not part of the server-side
	 * bookkeeping; the content hash covers it in UTC-normalized form (D10).
	 */
	@Column(name = "occurred_at", nullable = false)
	private OffsetDateTime occurredAt;

	/**
	 * Service receipt time (D11): database clock at insert, never provided by the client
	 * and never part of the content hash. Returned by the API.
	 */
	@Generated
	@Column(name = "received_at", nullable = false, insertable = false, updatable = false)
	private OffsetDateTime receivedAt;

	/**
	 * Optional client metadata (D1) in the real {@code jsonb} column. {@code null} means
	 * "no metadata" (an absent field and an explicit JSON null are the same content, D10).
	 */
	@JdbcTypeCode(SqlTypes.JSON)
	@Column(name = "metadata")
	private JsonNode metadata;

	/**
	 * Lowercase hex SHA-256 over the canonical JSON of the content fields (D4/D10), computed
	 * by {@link EventContentHasher}. Internal value: compared on duplicate eventId to decide
	 * between an idempotent retry (equal hash) and a conflict (different hash); never
	 * returned by the API.
	 */
	@Column(name = "content_hash", nullable = false)
	private String contentHash;

	/**
	 * Row-insert bookkeeping timestamp (D11): database clock, not exposed by the API.
	 */
	@Generated
	@Column(name = "created_at", nullable = false, insertable = false, updatable = false)
	private OffsetDateTime createdAt;

	public Long getId() {
		return id;
	}

	public String getEventId() {
		return eventId;
	}

	public void setEventId(String eventId) {
		this.eventId = eventId;
	}

	public String getUserId() {
		return userId;
	}

	public void setUserId(String userId) {
		this.userId = userId;
	}

	public String getEventType() {
		return eventType;
	}

	public void setEventType(String eventType) {
		this.eventType = eventType;
	}

	public String getSource() {
		return source;
	}

	public void setSource(String source) {
		this.source = source;
	}

	public OffsetDateTime getOccurredAt() {
		return occurredAt;
	}

	public void setOccurredAt(OffsetDateTime occurredAt) {
		this.occurredAt = occurredAt;
	}

	public OffsetDateTime getReceivedAt() {
		return receivedAt;
	}

	public JsonNode getMetadata() {
		return metadata;
	}

	public void setMetadata(JsonNode metadata) {
		this.metadata = metadata;
	}

	public String getContentHash() {
		return contentHash;
	}

	public void setContentHash(String contentHash) {
		this.contentHash = contentHash;
	}

}
